export function findChordByNotes(notes) {
  if (!notes || notes.length === 0) return null;
  return CHORD_LIBRARY.find((c) => sameNotes(c.notes, notes)) || null;
}

export function findChordForJourneyLevel(levelId) {
  if (!levelId) return null;
  return CHORD_LIBRARY.find((c) => c.journeyLevelId === levelId) || null;
}

export function getRelatedChords(root) {
  if (!root) return [];
  return CHORD_LIBRARY.filter((c) => c.root === root);
}
